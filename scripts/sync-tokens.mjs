#!/usr/bin/env node
// One colour source (SPEC-v3 §3, §12 P0-3). Reads src/styles/tokens.css and writes the colours that cannot read CSS:
//   src/render/palette.generated.ts  every colour JS needs as hex (theme-color, tests)
//   src/render/palette.ts            the WebGL scene colours, as a marked literal block (three.js materials take hex)
//   index.html                       the boot screen and theme-color, painted before app.css loads
// Run by `npm run prebuild`. `node scripts/sync-tokens.mjs --check` exits 1 if either file is stale (used by the tests).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TOKENS = join(ROOT, 'src/styles/tokens.css')
const GENERATED = join(ROOT, 'src/render/palette.generated.ts')
const HTML = join(ROOT, 'index.html')
const PALETTE = join(ROOT, 'src/render/palette.ts')

/** OKLCH to an sRGB hex string (clamped; every token is in gamut). */
export function oklchToHex(L, C, H) {
  const h = (H * Math.PI) / 180
  const a = C * Math.cos(h)
  const b = C * Math.sin(h)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  const linear = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
  const encode = (v) => {
    const c = Math.min(1, Math.max(0, v))
    return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055
  }
  return '#' + linear.map((v) => Math.round(encode(v) * 255).toString(16).padStart(2, '0')).join('')
}

/** The opaque oklch() custom properties of one top-level rule, as hex. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`)
  if (start < 0) throw new Error(`tokens.css has no "${selector}" rule`)
  const body = css.slice(start, css.indexOf('\n}', start))
  const out = {}
  for (const [, name, L, C, H] of body.matchAll(/--([a-z0-9-]+):\s*oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)\)/g)) {
    out[name] = oklchToHex(Number(L), Number(C), Number(H))
  }
  return out
}

export function readTokens(css = readFileSync(TOKENS, 'utf8')) {
  const light = block(css, ':root')
  const dark = { ...light, ...block(css, ":root[data-theme='dark']") }
  return { light, dark }
}

/** Token name -> scene palette field. */
const SCENE = { paper: 'paper', chrome: 'chrome', ink: 'ink', accent: 'accent', 'accent-mark': 'selection', wash: 'wash', waiting: 'waitingFill', muted: 'muted' }

export function generatedTs(tokens) {
  const theme = (t) =>
    Object.entries(SCENE)
      .map(([token, field]) => {
        if (!t[token]) throw new Error(`tokens.css is missing --${token}`)
        return `    ${field}: '${t[token]}',`
      })
      .join('\n')
  return `// Generated by scripts/sync-tokens.mjs from src/styles/tokens.css. Do not edit: change the token and rebuild.
export const TOKEN_COLORS = {
  light: {
${theme(tokens.light)}
  },
  dark: {
${theme(tokens.dark)}
  },
} as const

export type TokenColors = (typeof TOKEN_COLORS)['light']
`
}

const SCENE_START = '// sync-tokens:scene'
const SCENE_END = '// /sync-tokens:scene'
const SCENE_FIELDS = ['paper', 'ink', 'accent', 'selection', 'waitingFill']

/** The scene colours as literals in palette.ts, so the file reads on its own; generated, never hand-edited. */
export function paletteBlock(tokens) {
  const theme = (t) => {
    const row = Object.fromEntries(Object.entries(SCENE).map(([token, field]) => [field, t[token]]))
    return SCENE_FIELDS.map((f) => `${f}: '${row[f]}'`).join(', ')
  }
  return `${SCENE_START} (generated from src/styles/tokens.css: run npm run sync-tokens)
const SCENE_COLORS = {
  light: { ${theme(tokens.light)} },
  dark: { ${theme(tokens.dark)} },
} as const
${SCENE_END}`
}

export function syncedPalette(src, tokens) {
  const a = src.indexOf(SCENE_START)
  const b = src.indexOf(SCENE_END)
  if (a < 0 || b < a) throw new Error(`palette.ts needs the ${SCENE_START} … ${SCENE_END} markers`)
  return src.slice(0, a) + paletteBlock(tokens) + src.slice(b + SCENE_END.length)
}

const HEAD_START = '<!-- sync-tokens:head -->'
const HEAD_END = '<!-- /sync-tokens:head -->'

export function htmlBlock({ light, dark }) {
  return `${HEAD_START}
    <meta name="theme-color" content="${light.paper}" />
    <script>
      // Apply the saved or system theme before the first paint (the app keeps it in sync afterwards).
      try {
        const saved = localStorage.getItem('airforge.theme')
        const dark = saved ? saved === 'dark' : matchMedia('(prefers-color-scheme: dark)').matches
        document.documentElement.dataset.theme = dark ? 'dark' : 'light'
        if (dark) document.querySelector('meta[name="theme-color"]').content = '${dark.paper}'
      } catch {
        document.documentElement.dataset.theme = 'light'
      }
    </script>
    <style>
      html { background: ${light.paper}; color: ${light.muted}; }
      html[data-theme='dark'] { background: ${dark.paper}; color: ${dark.muted}; }
      .boot { margin: 0; height: 100vh; display: grid; place-items: center; font: 13px/18px 'Instrument Sans', ui-sans-serif, system-ui, sans-serif; }
    </style>
    ${HEAD_END}`
}

export function syncedHtml(html, tokens) {
  const a = html.indexOf(HEAD_START)
  const b = html.indexOf(HEAD_END)
  if (a < 0 || b < a) throw new Error(`index.html needs the ${HEAD_START} … ${HEAD_END} markers`)
  return html.slice(0, a) + htmlBlock(tokens) + html.slice(b + HEAD_END.length)
}

function main() {
  const check = process.argv.includes('--check')
  const tokens = readTokens()
  const outputs = [
    [GENERATED, generatedTs(tokens)],
    [HTML, syncedHtml(readFileSync(HTML, 'utf8'), tokens)],
    [PALETTE, syncedPalette(readFileSync(PALETTE, 'utf8'), tokens)],
  ]
  const stale = []
  for (const [file, next] of outputs) {
    let current = ''
    try {
      current = readFileSync(file, 'utf8')
    } catch {
      /* first run */
    }
    if (current === next) continue
    stale.push(file.slice(ROOT.length + 1))
    if (!check) writeFileSync(file, next)
  }
  if (check && stale.length) {
    console.error(`Stale colours (run npm run sync-tokens): ${stale.join(', ')}`)
    process.exit(1)
  }
  console.log(stale.length ? `sync-tokens: wrote ${stale.join(', ')}` : 'sync-tokens: up to date')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
